"""Draws the PrepBelt launcher icon from one geometry.

Writes the adaptive-icon vectors (background, foreground, monochrome), the
legacy mipmap PNGs and the 512 px Play Store icon. Run from the repository
root: `python tool/make_icon.py` (needs Pillow).

The design: five rounded ring segments in the belt ladder colours, Red at
the top running clockwise to Green, around a white check, on a midnight
gradient. Units are the 108 dp adaptive-icon viewport; everything sits
inside the 66 dp safe circle.
"""

import math
from pathlib import Path

from PIL import Image, ImageDraw

RES = Path("app/android/app/src/main/res")
PLAY = Path("docs/release/play-icon-512.png")

BG_FROM, BG_TO = "#1F2C4D", "#0A1122"  # top-left to bottom-right
LADDER = ["#E5484D", "#F2811D", "#F5B82E", "#8BC34A", "#34A85A"]
CHECK = "#FFFFFF"

C, R, RING_W = 54.0, 23.0, 7.0
GAP_DEG = 4.5  # visible gap between segments, after the round caps
CHECK_PTS = [(44.0, 54.5), (51.0, 61.5), (64.5, 47.5)]
CHECK_W = 6.0


def segments():
    """Yields (start_deg, end_deg, colour); 0 deg is 3 o'clock, clockwise."""
    cap = math.degrees((RING_W / 2) / R)
    span = 72.0 - GAP_DEG - 2 * cap
    for i, colour in enumerate(LADDER):
        start = -90.0 + i * 72.0 + GAP_DEG / 2 + cap
        yield start, start + span, colour


def pt(deg):
    a = math.radians(deg)
    return C + R * math.cos(a), C + R * math.sin(a)


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def vector(body, extra_ns=""):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/make_icon.py; edit that script, not this file. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"'
        f"{extra_ns}\n"
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        f"{body}</vector>\n"
    )


def stroke_path(d, colour):
    return (
        f'    <path android:pathData="{d}"\n'
        f'        android:strokeColor="{colour}" android:strokeWidth="{f(RING_W)}"\n'
        '        android:strokeLineCap="round" android:fillColor="#00000000"/>\n'
    )


def check_path(colour):
    (x0, y0), (x1, y1), (x2, y2) = CHECK_PTS
    d = f"M{f(x0)},{f(y0)} L{f(x1)},{f(y1)} L{f(x2)},{f(y2)}"
    return (
        f'    <path android:pathData="{d}"\n'
        f'        android:strokeColor="{colour}" android:strokeWidth="{f(CHECK_W)}"\n'
        '        android:strokeLineCap="round" android:strokeLineJoin="round"\n'
        '        android:fillColor="#00000000"/>\n'
    )


def arc_d(a, b):
    (x0, y0), (x1, y1) = pt(a), pt(b)
    return f"M{f(x0)},{f(y0)} A{f(R)},{f(R)} 0 0,1 {f(x1)},{f(y1)}"


def write_vectors():
    drawable = RES / "drawable"
    fg = "".join(stroke_path(arc_d(a, b), c) for a, b, c in segments())
    fg += check_path(CHECK)
    (drawable / "ic_launcher_foreground.xml").write_text(vector(fg), newline="\n")

    mono = "".join(stroke_path(arc_d(a, b), "#FFFFFFFF") for a, b, _ in segments())
    mono += check_path("#FFFFFFFF")
    (drawable / "ic_launcher_monochrome.xml").write_text(vector(mono), newline="\n")

    bg = (
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="linear"\n'
        '                android:startX="0" android:startY="0"\n'
        '                android:endX="108" android:endY="108">\n'
        f'                <item android:offset="0" android:color="{BG_FROM}"/>\n'
        f'                <item android:offset="1" android:color="{BG_TO}"/>\n'
        "            </gradient>\n"
        "        </aapt:attr>\n"
        "    </path>\n"
    )
    ns = '\n    xmlns:aapt="http://schemas.android.com/aapt"'
    (drawable / "ic_launcher_background.xml").write_text(vector(bg, ns), newline="\n")


def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))


def render(px, zoom=1.0, circle=False):
    """Renders the full icon at px square, zooming into the centre."""
    ss = 4
    n = px * ss
    s = n / 108 * zoom
    off = 54 - 54 / zoom

    def m(x, y):
        return (x - off) * s, (y - off) * s

    a, b = hex_rgb(BG_FROM), hex_rgb(BG_TO)
    v = Image.linear_gradient("L")  # 0 at the top, 255 at the bottom
    grad = Image.blend(v, v.transpose(Image.Transpose.ROTATE_90), 0.5).resize((n, n))
    im = Image.composite(Image.new("RGB", (n, n), b), Image.new("RGB", (n, n), a), grad)
    d = ImageDraw.Draw(im)

    def dot(x, y, w, colour):
        cx, cy = m(x, y)
        r = w / 2 * s
        d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=colour)

    x0, y0 = m(C - R - RING_W / 2, C - R - RING_W / 2)
    x1, y1 = m(C + R + RING_W / 2, C + R + RING_W / 2)
    for start, end, colour in segments():
        d.arc((x0, y0, x1, y1), start, end, fill=colour, width=round(RING_W * s))
        dot(*pt(start), RING_W, colour)
        dot(*pt(end), RING_W, colour)

    d.line([m(*p) for p in CHECK_PTS], fill=CHECK, width=round(CHECK_W * s))
    for p in CHECK_PTS:
        dot(*p, CHECK_W, CHECK)

    im = im.resize((px, px), Image.LANCZOS)
    if circle:
        mask = Image.new("L", (n, n), 0)
        ImageDraw.Draw(mask).ellipse((0, 0, n - 1, n - 1), fill=255)
        im.putalpha(mask.resize((px, px), Image.LANCZOS))
    return im


def write_pngs():
    # Legacy icons (unused at minSdk 26, kept for tools that read them).
    for folder, px in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
        render(px, zoom=108 / 72, circle=True).save(RES / f"mipmap-{folder}" / "ic_launcher.png")
    # Play shows the full square and masks the corners itself.
    render(512, zoom=1.25).save(PLAY)


if __name__ == "__main__":
    write_vectors()
    write_pngs()
    print("icon written")
